class TestOverallRiskUnaffected:
    def test_new_rules_are_additive_not_a_replacement_for_overall_risk(self, engine):
        text = (
            "The parties agree that either party may issue a press release regarding this "
            "Agreement without prior written consent."
        )
        result = engine.analyze(text)
        assert result["overall_risk"] == "high"
