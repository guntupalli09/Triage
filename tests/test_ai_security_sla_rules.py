class TestSecurityCertification:
    def test_fires_when_no_certification_is_named(self, engine):
        text = (
            "Vendor shall implement reasonable information security measures to protect "
            "Customer Data from unauthorized access."
        )
        assert "M_SECURITY_CERT_MISSING_01" in _rule_ids(engine, text)

    def test_does_not_fire_when_soc2_is_named(self, engine):
        text = (
            "Vendor maintains information security measures and is SOC 2 Type II certified, "
            "with reports available upon request."
        )
        assert "M_SECURITY_CERT_MISSING_01" not in _rule_ids(engine, text)

    def test_does_not_fire_on_generic_safeguard_language_unrelated_to_infosec(self, engine):
        # Regression: a bare "safeguards" topic pattern matched "Buyer will
        # take all appropriate measures to safeguard the CONFIDENTIALITY
        # of..." in a real PSA fixture -- ordinary confidentiality-
        # protection prose, nothing to do with an information-security
        # posture at all. Narrowed to require the
        # administrative/physical/technical qualifier.
        text = (
            "Buyer will take all appropriate measures to safeguard the confidentiality of "
            "Seller's proprietary information and avoid disclosure to unauthorized persons."
        )
        assert "M_SECURITY_CERT_MISSING_01" not in _rule_ids(engine, text)

    def test_does_not_fire_when_topic_is_out_of_scope(self, engine):
        text = "This Agreement governs the sale of widgets between the parties."
        assert "M_SECURITY_CERT_MISSING_01" not in _rule_ids(engine, text)


