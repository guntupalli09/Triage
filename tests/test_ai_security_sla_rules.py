"""
Regression tests for the v7.2 rule pack: AI governance, security
certification, and SLA response-time coverage (M_AI_OUTPUT_OWNERSHIP_01,
M_AI_HUMAN_REVIEW_01, M_SECURITY_CERT_MISSING_01, M_SLA_RESPONSE_TIME_01).

Each rule is REQUIRED_SECTION: only fires when its topic is genuinely in
scope for the document AND no protective language is found anywhere in
it — a document that never mentions the topic at all produces no finding
(the requirement doesn't apply), and a document that addresses the topic
correctly also produces no finding (see rules_engine.RuleClass docstring).
"""

import pytest
from rules_engine import RuleEngine


@pytest.fixture(scope="module")
def engine():
    return RuleEngine()


def _rule_ids(engine, text):
    return {f.rule_id for f in engine.analyze(text)["findings"]}


class TestAIOutputOwnership:
    def test_fires_when_ai_output_ownership_is_unaddressed(self, engine):
        text = (
            "This tool uses artificial intelligence to generate marketing content on behalf "
            "of Client under this Agreement."
        )
        assert "M_AI_OUTPUT_OWNERSHIP_01" in _rule_ids(engine, text)

    def test_does_not_fire_when_ownership_is_addressed(self, engine):
        text = (
            "Content generated using artificial intelligence under this Agreement shall be "
            "owned by Client."
        )
        assert "M_AI_OUTPUT_OWNERSHIP_01" not in _rule_ids(engine, text)

    def test_does_not_fire_when_topic_is_out_of_scope(self, engine):
        text = "This Agreement governs the sale of widgets between the parties."
        assert "M_AI_OUTPUT_OWNERSHIP_01" not in _rule_ids(engine, text)

    def test_does_not_falsely_flag_wellformed_ownership_language_as_adverse(self, engine):
        # Regression: an earlier version's chunked adverse-language pattern
        # matched ANY co-occurrence of an AI word and an ownership word,
        # regardless of polarity — so a well-drafted clause stating
        # ownership correctly still fired as if ownership were unaddressed.
        text = (
            "Any work product generated by artificial intelligence tools in the performance "
            "of the Services shall be owned by Client, and Client shall own all right, title, "
            "and interest therein."
        )
        assert "M_AI_OUTPUT_OWNERSHIP_01" not in _rule_ids(engine, text)


